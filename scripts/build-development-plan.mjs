#!/usr/bin/env node

// Validates the per-game estimates and writes the development plan:
//   node scripts/build-development-plan.mjs           # validate and write
//   node scripts/build-development-plan.mjs --check   # validate only
//   node scripts/build-development-plan.mjs --check td pk   # some families
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { FAMILIES, familyTitle } from './game-families.mjs';
import {
  computeEstimate,
  loadGames,
  validateGames,
} from './game-estimates.mjs';

const OUTPUT = 'docs/master-plan/development-plan.md';

const link = (game) =>
  `[${game.title}](concepts/pages/${game.id.toLowerCase()}.md)`;

function table(header, rows) {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

export function rankGames({ library, games }) {
  return games
    .map((game) => ({
      ...game,
      score: computeEstimate(game.estimate, library),
    }))
    .sort(
      (a, b) =>
        a.score.effortDays - b.score.effortDays ||
        a.score.risk - b.score.risk ||
        a.id.localeCompare(b.id)
    );
}

export function renderPlan({ library, games }) {
  const ranked = rankGames({ library, games });
  const byStart = [...ranked].sort(
    (a, b) =>
      a.score.startScore - b.score.startScore || a.id.localeCompare(b.id)
  );
  const toddlerFirst = ranked.filter((game) => game.estimate.toddler >= 4);
  const sharedLoc = library.shared.reduce((sum, item) => sum + item.loc, 0);
  const usage = new Map();
  for (const game of ranked) {
    for (const id of game.estimate.algorithms) {
      usage.set(id, (usage.get(id) || 0) + 1);
    }
  }
  const summary = Object.keys(FAMILIES).map((family) => {
    const list = ranked.filter((game) => game.family === family);
    const days = list.map((game) => game.score.effortDays);
    const median = [...days].sort((a, b) => a - b)[Math.floor(days.length / 2)];
    const easiest = list[0];
    return [
      `[${familyTitle(family)}](concepts/${family}.md)`,
      list.length,
      median,
      list.filter((game) => game.estimate.toddler >= 4).length,
      easiest ? link(easiest) : '—',
    ];
  });
  const fullRows = ranked.map((game, index) => [
    index + 1,
    link(game),
    game.id,
    familyTitle(game.family),
    `${game.estimate.minAge}+`,
    game.estimate.toddler,
    game.score.loc,
    game.score.assetHours,
    game.score.effortDays,
    game.score.risk,
  ]);
  const startRows = byStart
    .slice(0, 40)
    .map((game, index) => [
      index + 1,
      link(game),
      familyTitle(game.family),
      `${game.estimate.minAge}+`,
      game.estimate.toddler,
      game.score.effortDays,
      game.score.startScore,
      game.estimate.plan,
    ]);
  const algorithmRows = [...library.algorithms]
    .sort(
      (a, b) =>
        (usage.get(b.id) || 0) - (usage.get(a.id) || 0) ||
        a.id.localeCompare(b.id)
    )
    .map((a) => [
      `\`${a.id}\``,
      a.name,
      a.loc,
      a.difficulty,
      usage.get(a.id) || 0,
      a.description,
    ]);
  return `# Development plan — what to build first

Covers requirements **R66, R67 and R69** from the
[Raya feedback](../case-studies/issue-1/requirements.md#raya-shacados-toddlers-and-the-website-r55r76).
Generated by \`node scripts/build-development-plan.mjs\` from the per-game
estimates in [\`concepts/estimates/\`](concepts/estimates/library.json); do
not edit by hand. The same data is browsable and filterable on the
[website](README.md#website).

Every one of the **${ranked.length} game concepts** has an estimated plan: the
algorithms it needs (from a shared library of ${library.algorithms.length}),
its game-specific code size, its assets, the youngest age it suits and how
likely a toddler is to learn to play it. Each game page shows its own plan
in the "Estimated plan" section.

## How the scores work

- **Code size (LOC)** = the sum of the library sizes of the game's
  algorithms + game-specific glue code. It counts code for a first playable,
  polished version and excludes the shared platform below.
- **Asset hours** = Σ count × hours per asset type
  (${library.assets.map((a) => `${a.id} ${a.hours} h`).join(', ')}).
- **Effort days** = LOC / ${library.productivity.locPerDay} + asset hours / ${library.productivity.assetHoursPerDay}. One "day" is a
  focused person-day with the [AI pipeline](ai-pipeline.md); use it to
  compare games, not as a promise.
- **Risk** = the highest difficulty (1–5) among the game's algorithms.
- **Start score** = effort days × play factor of the toddler rating
  (${Object.entries(library.playFactor)
    .sort((a, b) => b[0] - a[0])
    .map(([rating, factor]) => `${rating} → ${factor}`)
    .join(', ')}). Games that are **easy to develop and easy to
  play** get the lowest scores and come first.

### Toddler learnability rubric

How likely a toddler is to learn to play the game without help, based on
the touch-gesture research in the
[research note](../case-studies/issue-1/data/research-raya-shacados.md#7-toddlers-and-screens-r68-r69)
(tap before drag before swipe; co-play under age 2):

${table(
  ['Rating', 'Meaning'],
  Object.entries(library.toddlerRubric)
    .sort((a, b) => b[0] - a[0])
    .map(([rating, text]) => [rating, text])
)}

### Shared platform (built once)

${table(
  ['Module', 'LOC'],
  library.shared.map((item) => [item.name, item.loc])
)}

The shared platform totals about **${sharedLoc} LOC**
(${Math.round((sharedLoc / library.productivity.locPerDay) * 10) / 10} days) and is built
with the first game.

## Start here — the 40 lowest start scores

${table(['#', 'Game', 'Collection', 'Age', 'Toddler', 'Days', 'Start score', 'First playable version'], startRows)}

## Toddler-first list

Games rated 4–5 on the rubric, easiest to develop first
(${toddlerFirst.length} games):

${toddlerFirst.map((game) => `${link(game)} (${game.score.effortDays} d, ${game.estimate.minAge}+)`).join(' · ')}

## Collections at a glance

${table(['Collection', 'Games', 'Median days', 'Toddler-friendly (4–5)', 'Easiest game'], summary)}

## All games sorted by development effort

${table(['#', 'Game', 'ID', 'Collection', 'Age', 'Toddler', 'LOC', 'Asset h', 'Days', 'Risk'], fullRows)}

## Algorithm library and reuse

Algorithms used by many games are the best candidates for shared packages
(see [infrastructure](infrastructure.md)).

${table(['ID', 'Algorithm', 'LOC', 'Difficulty', 'Games', 'What it does'], algorithmRows)}
`;
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const only = args.filter((arg) => !arg.startsWith('--'));
  const data = loadGames();
  const errors = validateGames(data).filter(
    (error) =>
      only.length === 0 ||
      only.some((family) => error.toLowerCase().startsWith(family))
  );
  if (errors.length) {
    console.error(errors.join('\n'));
    console.error(`${errors.length} estimate errors`);
    process.exit(1);
  }
  if (check) {
    console.log('Estimates are valid.');
  } else {
    writeFileSync(OUTPUT, renderPlan(data));
    console.log(`Wrote ${OUTPUT} for ${data.games.length} games.`);
  }
}
